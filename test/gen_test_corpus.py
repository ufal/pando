#!/usr/bin/env python3
"""A generated test corpus (JSONL v2 for `pando-index --format jsonl`), for test/fastpath_diff.py.

    gen_test_corpus.py OUT.jsonl [--tokens N] [--seed S]

The sample (test/data/sample.conllu, 1,174 tokens) fits in one bitmap chunk (2^16 positions), one
dependency window (2^18) and one partition, so the fast paths' boundaries never show there. This corpus
(default 600,000 tokens, deterministic for a seed) crosses them, and has what the sample lacks:

  * random but valid dependency trees (one root per sentence), a few long sentences (heads more than
    127 positions away: dep.head_rel8 exceptions);
  * UD-style attributes as in the sample (form, lemma, upos, xpos, deprel, feats as Key=Val|…, tuid)
    and the sample's region attributes (text_lang / langcode / genre / treebank, p_tuid), with the
    words test/fastpath_queries.txt asks for;
  * a multivalue attribute (`tags`: 0–3 of a few labels, `|`-joined) and feats declared kv_pipe;
  * `u` regions (speaker, gender) between text and s, and nested `phrase` regions.

Tokens outside any sentence cannot be written in JSONL (the reader adds them to the next sentence);
they are tested on TEITOK-built indexes instead.

Self-authored (random text), so it can live in the repository; the file itself is generated by the test.
"""

import argparse
import json
import random

UPOS_WEIGHTS = [("NOUN", 20), ("VERB", 12), ("ADJ", 8), ("DET", 10), ("ADP", 9), ("PRON", 6), ("ADV", 5),
                ("AUX", 4), ("PROPN", 4), ("CCONJ", 3), ("NUM", 2), ("PUNCT", 12), ("X", 1)]
DEPREL = {"NOUN": ["nsubj", "obj", "obl", "nmod", "iobj"], "PROPN": ["nsubj", "obj", "flat", "nmod"],
          "PRON": ["nsubj", "obj", "iobj", "nsubj:pass"], "VERB": ["ccomp", "xcomp", "advcl", "acl", "conj"],
          "ADJ": ["amod", "amod", "amod", "xcomp"], "DET": ["det"], "ADP": ["case"], "ADV": ["advmod"],
          "AUX": ["aux", "cop"], "CCONJ": ["cc"], "NUM": ["nummod"], "PUNCT": ["punct"], "X": ["dep"]}
FEATS = {"NOUN": {"Number": ["Sing", "Plur"], "Case": ["Nom", "Acc", "Gen"], "Gender": ["Masc", "Fem", "Neut"]},
         "PROPN": {"Number": ["Sing"]},
         "VERB": {"Tense": ["Past", "Pres"], "Person": ["1", "2", "3"], "VerbForm": ["Fin", "Inf", "Part"]},
         "ADJ": {"Degree": ["Pos", "Cmp", "Sup"], "Number": ["Sing", "Plur"]},
         "PRON": {"Person": ["1", "2", "3"], "PronType": ["Prs", "Dem", "Rel"]}, "DET": {"PronType": ["Art", "Dem"]}}
# words the query file asks for, by part of speech
SEED = {"NOUN": ["book", "house", "cat", "goodness", "kindness", "darkness", "Kraft", "Ordnung", "Zeitung"],
        "ADJ": ["good", "big", "unhappy", "unclear", "small"], "DET": ["the", "a", "een", "The"],
        "AUX": ["be", "have"], "VERB": ["be", "have", "read", "undo", "go", "walking", "sing"],
        "PRON": ["it", "they", "she"], "ADP": ["of", "in", "an"], "ADV": ["now", "unduly", "well"],
        "PROPN": ["Anna", "Bert"], "CCONJ": ["and", "or"], "NUM": ["two", "1999"], "PUNCT": [".", ",", "!"], "X": ["ab", "aab"]}
SYL = ["ka", "lo", "ne", "ri", "su", "ta", "mi", "do", "ve", "ul", "en", "ar", "is", "ung", "ness", "ing", "un", "th", "e"]
LANGS = [("English", "en", "ewt"), ("Czech", "cs", "pdt"), ("Dutch", "nl", "alpino"), ("German", "de", "hdt")]
GENRES = ["Book", "News", "Spoken", "Wiki"]
TAGS = ["PER", "LOC", "ORG", "MISC", "TIME"]


def vocab(rng):
    """Per part of speech: the seed words, then Zipf-ish generated lemmas."""
    v = {}
    for u, _ in UPOS_WEIGHTS:
        words = list(SEED.get(u, []))
        n = {"NOUN": 3000, "VERB": 1200, "ADJ": 800, "PROPN": 500, "ADV": 200}.get(u, 0)
        for _ in range(n):
            words.append("".join(rng.choice(SYL) for _ in range(rng.randint(1, 4))))
        v[u] = words
    return v


def pick_zipf(rng, words):
    i = int(rng.paretovariate(1.1)) - 1
    return words[min(i, len(words) - 1)]


def sentence(rng, voc, n):
    upos = rng.choices([u for u, _ in UPOS_WEIGHTS], [w for _, w in UPOS_WEIGHTS], k=n)
    verbs = [i for i, u in enumerate(upos) if u == "VERB"]
    root = rng.choice(verbs) if verbs else rng.randrange(n)
    # every other token attaches to an already attached one (a tree, no cycles); mostly nearby
    order = [i for i in range(n) if i != root]
    rng.shuffle(order)
    attached, head = [root], {root: 0}
    for i in order:
        near = [a for a in attached if abs(a - i) <= 6]
        h = rng.choice(near) if near and rng.random() < 0.8 else rng.choice(attached)
        head[i] = h + 1
        attached.append(i)
    toks = []
    for i, u in enumerate(upos):
        lemma = pick_zipf(rng, voc[u])
        form = lemma
        if u == "NOUN" and rng.random() < 0.3:
            form = lemma + "s"
        if u == "VERB" and rng.random() < 0.3:
            form = lemma + rng.choice(["ing", "ed"])
        if i == 0 and form[:1].isalpha():
            form = form[:1].upper() + form[1:]
        deprel = "root" if i == root else rng.choice(DEPREL[u])
        feats = "|".join(f"{k}={rng.choice(vals)}" for k, vals in sorted(FEATS.get(u, {}).items()) if rng.random() < 0.8) or "_"
        tags = "|".join(sorted(rng.sample(TAGS, rng.choice([0, 0, 0, 1, 1, 2, 3])))) or "_"
        toks.append({"tok_id": str(i + 1), "head": head[i] if i == root else None, "head_tok_id": None if i == root else str(head[i]),
                     "form": form, "lemma": lemma, "upos": u, "xpos": u[:2], "deprel": deprel, "feats": feats,
                     "tags": tags, "tuid": f"tu{rng.randrange(400)}" if rng.random() < 0.3 else "_"})
    return toks


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("out")
    ap.add_argument("--tokens", type=int, default=600_000)
    ap.add_argument("--seed", type=int, default=20261027)
    a = ap.parse_args()
    rng = random.Random(a.seed)
    voc = vocab(rng)
    positional = ["form", "lemma", "upos", "xpos", "deprel", "feats", "tags", "tuid"]
    pos = 0
    nsent = 0
    with open(a.out, "w", encoding="utf-8") as f:
        def w(o):
            f.write(json.dumps(o, ensure_ascii=False) + "\n")
        w({"type": "header", "version": 2, "positional": positional,
           "structural": ["s", "text", "u", "p", "phrase"],
           "region_attrs": {"text": ["id", "lang", "langcode", "genre", "treebank"], "u": ["who", "gender"], "p": ["tuid"], "s": ["id"], "phrase": ["cat"]},
           "nested": ["phrase"], "multivalue": ["tags"], "kv_pipe": ["feats"]})
        ntext = 0
        while pos < a.tokens:
            ntext += 1
            lang, code, tb = rng.choice(LANGS)
            tstart = pos
            for _ in range(rng.randint(3, 12)):            # utterances
                ustart = pos
                for _ in range(rng.randint(1, 6)):          # paragraphs
                    pstart = pos
                    for _ in range(rng.randint(1, 8)):      # sentences
                        n = rng.randint(400, 2500) if rng.random() < 0.004 else max(1, int(rng.gauss(18, 9)))
                        sstart = pos
                        for t in sentence(rng, voc, n):
                            ev = {"type": "token", "tok_id": t["tok_id"]}
                            if t["head"] is not None:
                                ev["head"] = 0
                            else:
                                ev["head_tok_id"] = t["head_tok_id"]
                            ev.update({k: t[k] for k in positional})
                            w(ev)
                            pos += 1
                        nsent += 1
                        # a nested phrase pair now and then (the inner inside the outer)
                        if n >= 6 and rng.random() < 0.3:
                            a0 = sstart + rng.randrange(n - 4)
                            w({"type": "region", "struct": "phrase", "start_pos": a0, "end_pos": a0 + 3, "attrs": {"cat": "NP"}})
                            w({"type": "region", "struct": "phrase", "start_pos": a0 + 1, "end_pos": a0 + 2, "attrs": {"cat": "AP"}})
                        w({"type": "region", "struct": "s", "start_pos": sstart, "end_pos": pos - 1, "attrs": {"id": f"s{nsent}"}})
                    w({"type": "region", "struct": "p", "start_pos": pstart, "end_pos": pos - 1, "attrs": {"tuid": f"p{rng.randrange(300)}"}})
                w({"type": "region", "struct": "u", "start_pos": ustart, "end_pos": pos - 1,
                   "attrs": {"who": f"spk{rng.randrange(40)}", "gender": rng.choice(["F", "M"])}})
            w({"type": "region", "struct": "text", "start_pos": tstart, "end_pos": pos - 1,
               "attrs": {"id": f"t{ntext}", "lang": lang, "langcode": code, "genre": rng.choice(GENRES), "treebank": tb}})
    print(f"{pos} tokens, {nsent} sentences, {ntext} texts")


if __name__ == "__main__":
    main()
